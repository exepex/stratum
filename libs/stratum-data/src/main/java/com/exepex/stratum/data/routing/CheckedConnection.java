package com.exepex.stratum.data.routing;

import java.sql.CallableStatement;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.experimental.Delegate;

/**
 * Checks, before each statement is created, that the current call wants the pool the connection was
 * opened on, so a transaction never reads or writes another pool than its own. Every other call
 * goes straight to the pool's connection, with no reflection. Two checked connections are equal
 * when they hold the same pool connection, opened on the same pool.
 */
@Builder
@EqualsAndHashCode
final class CheckedConnection implements Connection {

  /** The pool's connection, which receives every call. */
  @Delegate(excludes = StatementMethods.class)
  private final Connection connection;

  /** The pool the connection was opened on. */
  private final String pool;

  /** The pool each call wants. */
  private final PoolRouting routing;

  /**
   * Returns the pool's connection once the current call is checked against its pool. Each method
   * that creates a statement calls it first, through the methods Lombok writes from it.
   *
   * @return the pool's connection
   * @throws com.exepex.stratum.core.error.StratumException {@code SX-DATA-1008} if the current call
   *     wants another pool
   */
  @Delegate(types = StatementMethods.class)
  Connection checked() {
    routing.checkStatement(pool);
    return connection;
  }

  /** The 12 methods that create a statement, which check the pool before they reach the driver. */
  private interface StatementMethods {

    /** Mirrors {@link Connection#createStatement()}. */
    Statement createStatement() throws SQLException;

    /** Mirrors {@link Connection#createStatement(int, int)}. */
    Statement createStatement(int type, int concurrency) throws SQLException;

    /** Mirrors {@link Connection#createStatement(int, int, int)}. */
    Statement createStatement(int type, int concurrency, int holdability) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String)}. */
    PreparedStatement prepareStatement(String sql) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String, int)}. */
    PreparedStatement prepareStatement(String sql, int autoGeneratedKeys) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String, int[])}. */
    PreparedStatement prepareStatement(String sql, int... columnIndexes) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String, String[])}. */
    PreparedStatement prepareStatement(String sql, String... columnNames) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String, int, int)}. */
    PreparedStatement prepareStatement(String sql, int type, int concurrency) throws SQLException;

    /** Mirrors {@link Connection#prepareStatement(String, int, int, int)}. */
    PreparedStatement prepareStatement(String sql, int type, int concurrency, int holdability)
        throws SQLException;

    /** Mirrors {@link Connection#prepareCall(String)}. */
    CallableStatement prepareCall(String sql) throws SQLException;

    /** Mirrors {@link Connection#prepareCall(String, int, int)}. */
    CallableStatement prepareCall(String sql, int type, int concurrency) throws SQLException;

    /** Mirrors {@link Connection#prepareCall(String, int, int, int)}. */
    CallableStatement prepareCall(String sql, int type, int concurrency, int holdability)
        throws SQLException;
  }
}
